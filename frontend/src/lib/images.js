export function matchCuratedImage(name = '') {
  const n = String(name).toLowerCase();
  for (const [needle, key] of KEYWORDS) {
    if (n.includes(needle)) return IMAGES[key];
  }
  return null;
}

/** Credit lines for the footer, deduplicated. */
export function imageCredits() {
  const seen = new Set();
  const lines = [];
  for (const img of Object.values(IMAGES)) {
    if (!seen.has(img.credit)) {
      seen.add(img.credit);
      lines.push(img.credit);
    }
  }
  return lines;
}
