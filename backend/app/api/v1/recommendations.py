"""Interest-ranked recommendation endpoint."""

from __future__ import annotations

from typing import Annotated

from fastapi import APIRouter, Depends

from app.dependencies import CurrentUser, get_recommendation_service
from app.schemas.recommendations import RecommendationRequest, RecommendationResponse
from app.services.recommendation_service import RecommendationService

router = APIRouter(prefix="/recommendations", tags=["Recommendations"])


@router.post(
    "/",
    response_model=RecommendationResponse,
    summary="Recommend real attractions, restaurants, and hotels",
    description=(
        "Returns places sourced from Google Places, ranked deterministically by interest "
        "match, Google rating, review volume, price-level alignment, and open status. "
        "No place data is generated by an LLM."
    ),
    responses={503: {"description": "Google Maps is not configured"}},
)
async def recommend(
    payload: RecommendationRequest,
    _user: CurrentUser,
    service: Annotated[RecommendationService, Depends(get_recommendation_service)],
) -> RecommendationResponse:
    result = await service.recommend(payload)
    return RecommendationResponse(**result)
